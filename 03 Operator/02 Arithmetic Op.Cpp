/*
(1) Arithmetic Operator :-
                         --> Arithematic Operator in c++ are used to perform mathematical operations such as addition, subtraction , division and finding the remiander .

*/

#include <iostream>
using namespace std;

int main()
{
    int a = 10, b = 3;

    cout << "Addition: " << a + b << endl;       // 13
    cout << "Subtraction: " << a - b << endl;    // 7
    cout << "Multiplication: " << a * b << endl; // 30
    cout << "Division: " << a / b << endl;       // 3
    cout << "Modulus: " << a % b << endl;        // 1

    return 0;
}