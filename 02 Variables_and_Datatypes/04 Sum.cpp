// Wap to find sum of two numbers through user input?
#include <iostream>
using namespace std;
int main()
{
    int num1, num2, sum;
    cout << "Enter two numbers ";
    cin >> num1 >> num2;
    sum = num1 + num2;
    cout << "The sum of " << num1 << "  and " << num2 << "is : " << sum;
    return 0;
}